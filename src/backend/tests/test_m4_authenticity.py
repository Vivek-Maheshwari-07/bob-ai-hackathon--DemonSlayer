def _run_pipeline_for_section(
    section_body_text: str,
    mocked_verdict: str,
    missing_data_points=None,
):
    pipeline = CTDRagCheckerPipeline(exemplar_retriever=_make_exemplar_retriever())

    fake_result = AuthenticityResult(
        verdict=mocked_verdict,
        missing_data_points=missing_data_points or [],
        candidate_citation=None,
        exemplar_citations=["TEST FIXTURE excerpt"],
        reasoning=f"Mocked {mocked_verdict} verdict for wiring test.",
    )

    with patch.object(
        AuthenticityChecker, "check_content_authenticity", return_value=fake_result
    ) as mock_check:
        report = pipeline.run(
            {
                "submission_title": "Tier 3 Authenticity Wiring Test",
                "drug_name": "VIOXX",
                "sections": [
                    {
                        "section_id": "5.3.5",
                        "title": "Reports of Efficacy and Safety Studies",
                        "body_text": section_body_text,
                    },
                ],
            },
            enable_reasoner=False,
        )

    item = next(
        g
        for g in report.present_sections + report.partial_sections + report.missing_sections
        if g.section_id == "5.3.5"
    )
    return report, item, mock_check


# ─── GENERIC candidate: downgrades even though it clears substance gate ───


def test_generic_candidate_downgrades_to_partial_effective_status():
    report, item, mock_check = _run_pipeline_for_section(
        GENERIC_CANDIDATE_TEXT,
        mocked_verdict="GENERIC",
        missing_data_points=["sample size", "p-value", "named study identifier"],
    )

    # Confirm Tier 3 actually ran (exemplars were found and the checker was invoked).
    assert mock_check.called

    # Passed the substance gate (word count clears the floor) and Tier 1
    # matched it structurally — without Tier 3, this would be PRESENT.
    assert item.substance_gate_reason is None
    assert item.status == GapStatus.PRESENT

    # Tier 3 verdict recorded with its evidence.
    assert item.authenticity_verdict == "GENERIC"
    assert item.authenticity_evidence is not None
    assert "sample size" in item.authenticity_evidence["missing_data_points"]
    assert item.authenticity_evidence["source_citations"] == ["TEST FIXTURE — not a real regulatory citation"]

    # The effective score used in the weighted formula is downgraded to
    # PARTIAL (0.5) despite Tier 1 saying PRESENT.
    scorer = CompletenessScorer()
    assert scorer._effective_status_score(item) == CompletenessScorer.WEIGHT_PARTIAL


def test_insufficient_verdict_downgrades_to_missing_effective_status():
    report, item, mock_check = _run_pipeline_for_section(
        GENERIC_CANDIDATE_TEXT,
        mocked_verdict="INSUFFICIENT",
        missing_data_points=["everything concrete"],
    )
    assert mock_check.called
    assert item.authenticity_verdict == "INSUFFICIENT"

    scorer = CompletenessScorer()
    assert scorer._effective_status_score(item) == CompletenessScorer.WEIGHT_MISSING
    # With this section forced to an effective 0.0 and every other KB
    # requirement genuinely MISSING (a single-section dossier), the overall
    # weighted score has nothing earning any points at all.
    assert report.overall_completeness == 0.0


# ─── Critical false-positive guard: genuinely substantive content ─────────


def test_substantive_verdict_does_not_downgrade_real_content():
    report, item, mock_check = _run_pipeline_for_section(
        SUBSTANTIVE_CANDIDATE_TEXT,
        mocked_verdict="SUBSTANTIVE",
        missing_data_points=[],
    )
    assert mock_check.called
    assert item.authenticity_verdict == "SUBSTANTIVE"
    assert item.status == GapStatus.PRESENT

    # SUBSTANTIVE leaves the prior tier's effective status unchanged — still
    # counts as fully PRESENT for scoring.
    scorer = CompletenessScorer()
    assert scorer._effective_status_score(item) == CompletenessScorer.WEIGHT_PRESENT


def test_downgrade_ordering_end_to_end():
    """A single, direct end-to-end comparison: for the identical candidate
    text and exemplar, only the mocked verdict changes — overall readiness
    must strictly decrease as the verdict worsens."""
    report_substantive, _, _ = _run_pipeline_for_section(SUBSTANTIVE_CANDIDATE_TEXT, "SUBSTANTIVE")
    report_generic, _, _ = _run_pipeline_for_section(SUBSTANTIVE_CANDIDATE_TEXT, "GENERIC")
    report_insufficient, _, _ = _run_pipeline_for_section(SUBSTANTIVE_CANDIDATE_TEXT, "INSUFFICIENT")

    assert (
        report_substantive.overall_completeness
        > report_generic.overall_completeness
        > report_insufficient.overall_completeness
        == 0.0
    )


# ─── Gating conditions: Tier 3 must not run outside its intended scope ────


def test_tier3_skips_sections_forced_missing_by_substance_gate():
    """A section with almost no body_text is forced MISSING by the substance
    gate before Tier 3 ever gets a chance to run — even with exemplars
    available and the checker mocked to return a verdict, it must not fire."""
    pipeline = CTDRagCheckerPipeline(exemplar_retriever=_make_exemplar_retriever())
    fake_result = AuthenticityResult(
        verdict="SUBSTANTIVE", missing_data_points=[], candidate_citation=None,
        exemplar_citations=[], reasoning="should never be reached",
    )

    with patch.object(
        AuthenticityChecker, "check_content_authenticity", return_value=fake_result
    ) as mock_check:
        report = pipeline.run(
            {
                "submission_title": "Thin Section Test",
                "sections": [
                    {"section_id": "5.3.5", "title": "CSR", "body_text": "Only a few words here."},
                ],
            },
            enable_reasoner=False,
        )

    mock_check.assert_not_called()
    item = next(g for g in report.missing_sections if g.section_id == "5.3.5")
    assert item.substance_gate_reason is not None
    assert item.authenticity_verdict is None


def test_tier3_skips_when_no_exemplars_for_section():
    """With the production-shipped placeholder corpus (no real exemplars for
    any section), Tier 3 must no-op entirely, even for a section that
    otherwise passes the substance gate — this is the "empty corpus degrades
    cleanly" contract."""
    pipeline = CTDRagCheckerPipeline()  # default ExemplarRetriever loads the real (placeholder) corpus
    assert pipeline.exemplar_retriever.is_available is False

    with patch.object(AuthenticityChecker, "check_content_authenticity") as mock_check:
        report = pipeline.run(
            {
                "submission_title": "Placeholder Corpus Test",
                "sections": [
                    {
                        "section_id": "5.3.5",
                        "title": "Reports of Efficacy and Safety Studies",
                        "body_text": SUBSTANTIVE_CANDIDATE_TEXT,
                    },
                ],
            },
            enable_reasoner=False,
        )

    mock_check.assert_not_called()
    item = next(g for g in report.present_sections + report.partial_sections if g.section_id == "5.3.5")
    assert item.authenticity_verdict is None
    assert item.authenticity_evidence is None


