"""Tests for Tier 3 content-authenticity checking (exemplar_retriever.py +
authenticity_checker.py + pipeline/completeness wiring).

Tier 3 catches a failure mode Tiers 1/2 and the substance gate all miss: a
long, well-written, correctly-keyworded section that clears the word-count
floor and could even answer Tier 2's yes/no checkpoints in the abstract, but
contains zero concrete data points — grounded by comparing it against a real
regulatory-document exemplar rather than judging it in isolation.

The production exemplar corpus (knowledge/exemplar_corpus.json) ships as
placeholders (no real sourced text yet), so these tests inject their own
in-memory test corpus via ExemplarRetriever's `corpus=` constructor param and
mock AuthenticityChecker.check_content_authenticity to exercise the pipeline
wiring/downgrade logic deterministically, without requiring a live Gemini key
or fabricating claims about real regulatory documents.
"""

